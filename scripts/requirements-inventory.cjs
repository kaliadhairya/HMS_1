// Requirement-to-test inventory (completion A1). Generates
// docs/clinical-final/REQUIREMENTS_INVENTORY.md from:
//  - the blueprint 5.3 acceptance scenarios as recorded in docs/clinical-final/ACCEPTANCE_MATRIX.md
//    (each row names its suites; this lists the step names those suites actually contain), and
//  - the blueprint 3.10 interface table (below), mapped to the published v2 contract
//    (backend/contracts/v2.openapi.json) and to the suites that call each operation.
// Usage: node scripts/requirements-inventory.cjs          write the inventory
//        node scripts/requirements-inventory.cjs --check  fail on a GAP row, a named suite that does
//                                                          not exist, an interface without an operation
//                                                          or a calling suite, or a stale inventory
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const E2E = path.join(ROOT, 'e2e');
const MATRIX = path.join(ROOT, 'docs/clinical-final/ACCEPTANCE_MATRIX.md');
const OUT = path.join(ROOT, 'docs/clinical-final/REQUIREMENTS_INVENTORY.md');
const spec = JSON.parse(fs.readFileSync(path.join(ROOT, 'backend/contracts/v2.openapi.json'), 'utf8'));

// Blueprint 3.10, "Public API and compatibility changes": each required interface and the v2
// operations that implement it (operationId in the published contract).
const INTERFACES = [
  ['POST /appointments, POST /appointments/{id}/reschedule', 'Resource interval validation and idempotency', ['bookAppointment', 'rescheduleAppointment', 'cancelAppointment']],
  ['POST /admissions, POST /admissions/{id}/transfers', 'Atomic ADT transitions and occupancy enforcement', ['admitPatient', 'transferAdmission', 'dischargeAdmission']],
  ['PUT /clinical-documents/{id}/draft, POST /clinical-documents/{id}/sign', 'Expected-version enforcement and immutable signing', ['saveDocumentDraft', 'signDocument']],
  ['POST /medication-orders/{id}/sign, /hold, /resume, /discontinue', 'Explicit privileges, clinical context and transition guards', ['signMedicationOrder', 'holdMedicationOrder', 'resumeMedicationOrder', 'discontinueMedicationOrder']],
  ['POST /dispenses', 'Required order-line identity and per-line fulfillment', ['createDispense']],
  ['POST /administrations', 'Schedule/order version, actual administration details and verification evidence', ['createAdministration']],
  ['POST /specimens, /receive, /reject', 'Accession identity and custody transitions', ['createSpecimen', 'receiveSpecimen', 'rejectSpecimen']],
  ['POST /results/{id}/verify, POST /reports/{id}/release', 'Authorized result lifecycle', ['verifyLabResult', 'releaseLabReport']],
  ['POST /critical-results/{id}/acknowledgments', 'Recipient acknowledgment; clinical action recorded separately', ['acknowledgeCriticalResult', 'recordCriticalResultAction']],
  ['POST /billing-accounts/{id}/invoices', 'Source-linked immutable invoice', ['issueInvoice']],
  ['POST /payments, /deposit-allocations, /credit-notes, /refunds', 'Distinct financial commands with idempotency and authorization', ['startPayment', 'allocateDeposit', 'createCreditNote', 'requestRefund']],
  ['GET /events?cursor=...', 'Authorized recovery after missed notifications', ['readEvents']],
];

const suites = new Map(fs.readdirSync(E2E).filter((f) => f.endsWith('.e2e.js')).map((f) => [f.replace(/\.e2e\.js$/, ''), fs.readFileSync(path.join(E2E, f), 'utf8')]));
// Step titles as written in the suite (single, double or template quotes, possibly on the next line).
const steps = (src) => [...src.matchAll(/step\(\s*(['"`])((?:\\.|(?!\1).)*)\1/gs)].map((m) => m[2].replace(/\\(['"`])/g, '$1'));
const md = (text) => String(text).replace(/\|/g, '\\|');

const problems = [];
const lines = [
  '# Requirement-to-test inventory',
  '',
  'Generated by `scripts/requirements-inventory.cjs` (completion A1); do not edit by hand.',
  'Run `node scripts/requirements-inventory.cjs --check` to verify it is current and complete.',
  '',
  '## Blueprint 5.3 acceptance scenarios',
  '',
  'Rows and suites come from `ACCEPTANCE_MATRIX.md`; the steps are the suites\' own step names.',
  '',
];
const rows = fs.readFileSync(MATRIX, 'utf8').split('\n').filter((l) => /^\| [^-|][^|]*\| /.test(l) && !l.startsWith('| Area'));
for (const row of rows) {
  const [area, scenario, suiteCell, status] = row.split('|').slice(1, -1).map((c) => c.trim());
  const named = [...suiteCell.matchAll(/\b([a-z][A-Za-z0-9]+)\b/g)].map((m) => m[1]).filter((n) => suites.has(n));
  if (/^GAP/.test(status)) problems.push(`5.3 ${area}: "${scenario}" is a GAP`);
  if (!named.length && !/not a suite|external/i.test(suiteCell + status)) problems.push(`5.3 ${area}: "${scenario}" names no existing suite`);
  lines.push(`### ${area}: ${scenario}`, '', `Status: ${status}`, '');
  for (const n of [...new Set(named)]) {
    const s = steps(suites.get(n));
    lines.push(`- \`e2e/${n}.e2e.js\` (${s.length} steps)`);
    for (const t of s) lines.push(`  - ${md(t)}`);
  }
  if (!named.length) lines.push(`- ${suiteCell}`);
  lines.push('');
}

lines.push('## Blueprint 3.10 interfaces', '', '| Interface | Required behavior | v2 operations | Suites calling them |', '|---|---|---|---|');
const operations = new Map();
for (const [p, methods] of Object.entries(spec.paths)) for (const [m, op] of Object.entries(methods)) operations.set(op.operationId, { method: m.toUpperCase(), path: p });
for (const [iface, behavior, ids] of INTERFACES) {
  const cells = [];
  const callers = new Set();
  for (const id of ids) {
    const op = operations.get(id);
    if (!op) { problems.push(`3.10 ${iface}: operation ${id} is not in the published contract`); continue; }
    cells.push(`\`${op.method} ${op.path}\``);
    // A suite calls the operation when it uses its path under /v2 (path parameters as any segment),
    // written whole, joined from pieces ('/v2/x/'+id+'/y'), or through a helper that adds '/v2'.
    const body = op.path.replace(/\{[^}]+\}/g, '[^\'"`/?]+').replace(/\//g, '\\/');
    const whole = new RegExp(`/v2${body}(?![A-Za-z-])`), bare = new RegExp(`['"\`]${body}(?![A-Za-z-])`);
    for (const [n, src] of suites) {
      const flat = src.replace(/\$\{[^}]*\}/g, 'X').replace(/(['"`])\s*\+\s*[A-Za-z_$][\w$.]*\s*\+\s*\1/g, 'X');
      if (whole.test(flat) || (/['"`]\/v2['"`]\s*\+/.test(src) && bare.test(flat))) callers.add(n);
    }
  }
  if (!callers.size) problems.push(`3.10 ${iface}: no suite calls its operations`);
  lines.push(`| ${md(iface)} | ${md(behavior)} | ${cells.join(', ')} | ${[...callers].sort().map((n) => `\`${n}\``).join(', ')} |`);
}
lines.push('');
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) problems.push('REQUIREMENTS_INVENTORY.md is stale: run node scripts/requirements-inventory.cjs');
  if (problems.length) { console.error(problems.map((p) => `- ${p}`).join('\n')); process.exit(1); }
  console.log(`inventory current: ${rows.length} acceptance rows, ${INTERFACES.length} interfaces`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}${problems.length ? `; ${problems.length} problems:\n${problems.map((p) => `- ${p}`).join('\n')}` : ''}`);
}
